// A simulated player: its faction, which army it fields and which skills it picks.
type policy struct {
	name    string
	faction sim.Faction
	target  [3]int // wanted melee, ranged and caster units (veterans count toward it)
	picks   string // "random" or "best" (highest measured impact first)
}

// Skill preference for the "best" policy: each unit's skills by their
// measured impact (the skills experiment, at bestOrderN battles per row),
// worked out once, the first time a run needs it.
var (
	bestOrder     map[sim.Class][]sim.Skill
	bestOrderOnce sync.Once
)

const bestOrderN = 400

func best(c sim.Class) []sim.Skill {
	bestOrderOnce.Do(func() {
		bestOrder = map[sim.Class][]sim.Skill{}
		_, rows := Skills(bestOrderN) // rows come sorted by win rate within each faction
		for _, r := range rows {
			for _, d := range sim.RosterOf(r.class).Skills {
				if d.Name == r.name {
					bestOrder[r.class] = append(bestOrder[r.class], d.Skill)
				}
			}
		}
	})
	return bestOrder[c]
}

// redMode: how Red's army is chosen each match.
type redMode func(seed uint64, blue []sim.UnitSpec, skills int) sim.Army

// randomRed is the game today: the sim generates Red from the seed.
func randomRed(uint64, []sim.UnitSpec, int) sim.Army { return sim.Army{} }

const maxMatches = 40

type runResult struct {
	wins     int
	matchWin []bool // per match played: won?
	vetStars []int  // veteran skills at the start of each match
}

func playRun(runSeed uint64, p policy, red redMode, curve []int) runResult {
	var vets []sim.UnitSpec
	var res runResult
	rng := sim.NewRNG(runSeed ^ 0x5eed)
	for m := 1; m <= maxMatches; m++ {
		seed := runSeed*1000 + uint64(m)
		stars := 0 // abilities above level 1: what Red is matched to
		for _, v := range vets {
			stars += len(v.Skills) - 1
		}
		// army: veterans first, then recruits up to the target mix
		blue := append([]sim.UnitSpec(nil), vets...)
		units := trio(p.faction)
		have := [3]int{}
		for _, v := range vets {
			have[roleOf(v.Class)]++
		}
		for r := melee; r <= caster && len(blue) < sim.ArmySize; r++ {
			for have[r] < p.target[r] && len(blue) < sim.ArmySize {
				u := sim.UnitSpec{Class: units[r]}
				u.Skills = []sim.Skill{pickSkill(u, p.picks, rng)} // level 1
				blue = append(blue, u)
				have[r]++
			}
		}
		for len(blue) < sim.ArmySize { // veterans pushed the mix over: fill with melee
			u := sim.UnitSpec{Class: units[melee]}
			u.Skills = []sim.Skill{pickSkill(u, p.picks, rng)}
			blue = append(blue, u)
		}
		in := input(seed)
		in.BlueFaction = p.faction
		in.Blue = sim.Army{Formation: sim.F3x2, Units: blue}
		in.RedHealthPct = healthCurve(curve, m)
		// Red: generated by the sim from the seed (as the server does), or chosen by the mode
		if ra := red(seed, blue, stars); len(ra.Units) == 0 {
			in.RedSkills = stars
		} else {
			in.Red = ra
		}
		o, err := sim.Run(in)
		if err != nil {
			panic(err)
		}
		res.vetStars = append(res.vetStars, stars)
		won := o.Result == sim.BlueWin
		res.matchWin = append(res.matchWin, won)
		if !won {
			return res
		}
		res.wins++
		// survivors become veterans and learn one skill each
		vets = vets[:0:0]
		for _, s := range o.Survivors {
			if s.Index < len(blue) {
				u := sim.UnitSpec{Class: blue[s.Index].Class, Skills: append([]sim.Skill(nil), blue[s.Index].Skills...)}
				if len(u.Skills) < sim.MaxLevel {
					u.Skills = append(u.Skills, pickSkill(u, p.picks, rng))
				}
				vets = append(vets, u)
			}
		}
	}
	return res
}

func pickSkill(u sim.UnitSpec, how string, rng *sim.RNG) sim.Skill {
	var left []sim.Skill
	var order []sim.Skill
	if how == "best" {
		order = best(u.Class)
	} else {
		for _, d := range sim.RosterOf(u.Class).Skills {
			order = append(order, d.Skill)
		}
	}
	for _, s := range order {
		known := false
		for _, k := range u.Skills {
			known = known || k == s
		}
		if !known {
			left = append(left, s)
		}
	}
	if how == "random" {
		return left[rng.IntN(len(left))]
	}
	return left[0]
}

func playRuns(n int, base uint64, p policy, red redMode, curve []int) []runResult {
	out := make([]runResult, n)
	next := make(chan int)
	var wg sync.WaitGroup
	for w := 0; w < runtime.NumCPU(); w++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for i := range next {
				out[i] = playRun(base+uint64(i), p, red, curve)
			}
		}()
	}
	for i := 0; i < n; i++ {
		next <- i
	}
	close(next)
	wg.Wait()
	return out
}

// Runs: run length and per-match win rate for a few policies and Red modes.
func Runs(n int, reds map[string]redMode) string {
	var policies []policy
	for _, f := range playable() {
		t := factionTitle(f)
		policies = append(policies,
			policy{t + " 2·2·1, random picks", f, [3]int{2, 2, 1}, "random"},
			policy{t + " 2·2·1, best picks", f, [3]int{2, 2, 1}, "best"},
			policy{t + " 1·2·2, best picks", f, [3]int{1, 2, 2}, "best"},
			policy{t + " 3·0·2, best picks", f, [3]int{3, 0, 2}, "best"},
		)
	}
	var names []string
	for k := range reds {
		names = append(names, k)
	}
	sort.Strings(names)
	var b strings.Builder
	for _, rn := range names {
		fmt.Fprintf(&b, "### Red: %s\n\n| Player policy | Avg wins | Median | Reach match 5 | Reach 10 | Win%% m1 | m2 | m3 | m4–6 | m7+ | Avg ★ at m5 |\n|---|---|---|---|---|---|---|---|---|---|---|\n", rn)
		for _, p := range policies {
			curve := gameCurve // the game's easing, except for modes that replace it
			if strings.HasPrefix(rn, "ramp") {
				curve = nil
			}
			rs := playRuns(n, 500_000, p, reds[rn], curve)
			fmt.Fprintf(&b, "| %s | %s |\n", p.name, summarise(rs))
		}
		b.WriteString("\n")
	}
	fmt.Fprintf(&b, "%d runs per row; a run ends at its first loss (cap %d matches). Mixes are melee·ranged·caster; \"best picks\" take each unit's skills in the order of the skill-impact table. \"Win%% mX\" is the win rate of match X among runs that reached it.\n", n, maxMatches)
	return b.String()
}

func summarise(rs []runResult) string {
	var wins []int
	reach := func(k int) float64 {
		c := 0
		for _, r := range rs {
			if len(r.matchWin) >= k {
				c++
			}
		}
		return float64(c) / float64(len(rs))
	}
	rate := func(lo, hi int) string {
		w, n := 0, 0
		for _, r := range rs {
			for i, won := range r.matchWin {
				if m := i + 1; m >= lo && m <= hi {
					n++
					if won {
						w++
					}
				}
			}
		}
		if n < 30 {
			return "–"
		}
		return pct(float64(w) / float64(n))
	}
	total, stars5, n5 := 0, 0, 0
	for _, r := range rs {
		wins = append(wins, r.wins)
		total += r.wins
		if len(r.vetStars) >= 5 {
			stars5 += r.vetStars[4]
			n5++
		}
	}
	sort.Ints(wins)
	avgStars := "–"
	if n5 > 0 {
		avgStars = fmt.Sprintf("%.1f", float64(stars5)/float64(n5))
	}
	return fmt.Sprintf("%.2f | %d | %s | %s | %s | %s | %s | %s | %s | %s",
		float64(total)/float64(len(rs)), wins[len(wins)/2], pct(reach(5)), pct(reach(10)),
		rate(1, 1), rate(2, 2), rate(3, 3), rate(4, 6), rate(7, maxMatches), avgStars)
}

var redModes = map[string]redMode{
	"random (the game)":              randomRed,
	"counter-picks (50% of units)":   counterRed,
	"ramp: 3 units m1, 4 m2, then 5": rampRed,
	"ramp: 4 units m1–2, then 5":     ramp4Red,
}

// ramp4Red: 4 Red units in matches 1 and 2, then 5.
func ramp4Red(seed uint64, _ []sim.UnitSpec, skills int) sim.Army {
	a := sim.RedArmy(seed, skills)
	if seed%1000 <= 2 {
		a.Units = a.Units[:4]
	}
	return a
}

// counters[r] is the role that beats role r: casters beat melee, melee beat
// ranged, ranged beat casters.
var counters = [3]int{melee: caster, ranged: melee, caster: ranged}

// spreadSkills gives every unit one ability (level 1), then hands out n more
// at random, never twice on one unit and up to the top level (as RedArmy).
func spreadSkills(r *sim.RNG, units []sim.UnitSpec, n int) {
	for i := range units {
		learnRandom(r, &units[i])
	}
	for ; n > 0; n-- {
		var open []int
		for i, u := range units {
			if len(u.Skills) < sim.MaxLevel {
				open = append(open, i)
			}
		}
		if len(open) == 0 {
			return
		}
		learnRandom(r, &units[open[r.IntN(len(open))]])
	}
}

func learnRandom(r *sim.RNG, u *sim.UnitSpec) {
	var left []sim.Skill
	for _, d := range sim.RosterOf(u.Class).Skills {
		known := false
		for _, k := range u.Skills {
			known = known || k == d.Skill
		}
		if !known {
			left = append(left, d.Skill)
		}
	}
	u.Skills = append(u.Skills, left[r.IntN(len(left))])
}

// counterRed: Red's faction as the game draws it; each Red unit is, with 50%
// chance, its unit of the role that counters the matching Blue unit's,
// otherwise a random one of its units.
func counterRed(seed uint64, blue []sim.UnitSpec, skills int) sim.Army {
	r := sim.NewRNG(seed ^ 0xc0)
	units := trio(sim.RedFactionFor(seed))
	a := sim.Army{Formation: sim.Presets[r.IntN(len(sim.Presets))]}
	for i := 0; i < sim.ArmySize; i++ {
		role := r.IntN(3)
		if r.IntN(2) == 0 && i < len(blue) {
			role = counters[roleOf(blue[i].Class)]
		}
		a.Units = append(a.Units, sim.UnitSpec{Class: units[role]})
	}
	sort.SliceStable(a.Units, func(i, j int) bool { return a.Units[i].Class < a.Units[j].Class })
	spreadSkills(r, a.Units, skills)
	return a
}

// rampRed: the game's own Red army, cut to 3 units in match 1 and 4 in match 2.
func rampRed(seed uint64, _ []sim.UnitSpec, skills int) sim.Army {
	a := sim.RedArmy(seed, skills)
	match := int(seed % 1000)
	if size := match + 2; size < len(a.Units) {
		a.Units = a.Units[:size]
	}
	return a
}

// gameCurve is the game's own easing (sim.RunRedHealth) for the first matches.
var gameCurve = []int{sim.RunRedHealth(1), sim.RunRedHealth(2), sim.RunRedHealth(3)}

// healthCurve returns Red's health % for match m (1-based); nil means 100%.
func healthCurve(curve []int, m int) int {
	if m-1 < len(curve) {
		return curve[m-1]
	}
	return 0
}

// RunCurves: the game's random Red with different early-match health curves.
func RunCurves(n int) string {
	curves := []struct {
		name  string
		curve []int
	}{
		{"none (0.4.0 before run-balance)", nil},
		{"90/95%", []int{90, 95}},
		{"85/90/95% (the game now)", gameCurve},
		{"80/88/94%", []int{80, 88, 94}},
		{"80/85/90/95%", []int{80, 85, 90, 95}},
	}
	var b strings.Builder
	b.WriteString("Player: each faction's 2·2·1 (melee·ranged·caster), best picks; Red: the game's random army with its health scaled in the first matches.\n\n| Faction | Red health curve | Avg wins | Median | Reach match 5 | Reach 10 | Win% m1 | m2 | m3 | m4–6 | m7+ | Avg ★ at m5 |\n|---|---|---|---|---|---|---|---|---|---|---|---|\n")
	for _, f := range playable() {
		p := policy{factionTitle(f) + " 2·2·1, best picks", f, [3]int{2, 2, 1}, "best"}
		for _, c := range curves {
			fmt.Fprintf(&b, "| %s | %s | %s |\n", factionTitle(f), c.name, summarise(playRuns(n, 600_000, p, randomRed, c.curve)))
		}
	}
	fmt.Fprintf(&b, "\n%d runs per row.\n", n)
	return b.String()
}

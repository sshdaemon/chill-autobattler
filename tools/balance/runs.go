// A simulated player: which army it fields and which skills it picks.
type policy struct {
	name   string
	target [3]int // wanted warriors, archers, mages (veterans count toward it)
	picks  string // "random" or "best" (highest measured impact first)
}

// Skill preference for the "best" policy, from the 0.4.0 skill-impact table.
var bestOrder = map[sim.Class][]sim.Skill{
	sim.Warrior: {sim.SkillSpeed, sim.SkillDash, sim.SkillHealth, sim.SkillExecute, sim.SkillDamage},
	sim.Archer:  {sim.SkillLob, sim.SkillDamage, sim.SkillExecute, sim.SkillHealth, sim.SkillRange},
	sim.Mage:    {sim.SkillBlast, sim.SkillDamage, sim.SkillHealth, sim.SkillBlink, sim.SkillFrost},
}

// redMode: how Red's army is chosen each match.
type redMode func(seed uint64, blue []sim.UnitSpec, skills int) sim.Army

// randomRed is the game today: the sim generates Red from the seed.
func randomRed(uint64, []sim.UnitSpec, int) sim.Army { return sim.Army{} }

const maxMatches = 40

type runResult struct {
	wins     int
	matchWin []bool // per match played: won?
	vetStars []int  // veteran skills at the start of each match
}

func playRun(runSeed uint64, p policy, red redMode, curve []int) runResult {
	var vets []sim.UnitSpec
	var res runResult
	rng := sim.NewRNG(runSeed ^ 0x5eed)
	for m := 1; m <= maxMatches; m++ {
		seed := runSeed*1000 + uint64(m)
		stars := 0
		for _, v := range vets {
			stars += len(v.Skills)
		}
		// army: veterans first, then recruits up to the target mix
		blue := append([]sim.UnitSpec(nil), vets...)
		have := [3]int{}
		for _, v := range vets {
			have[v.Class]++
		}
		for c := sim.Warrior; c <= sim.Mage && len(blue) < sim.ArmySize; c++ {
			for have[c] < p.target[c] && len(blue) < sim.ArmySize {
				blue = append(blue, sim.UnitSpec{Class: c})
				have[c]++
			}
		}
		for len(blue) < sim.ArmySize { // veterans pushed the mix over: fill with warriors
			blue = append(blue, sim.UnitSpec{Class: sim.Warrior})
		}
		in := input(seed)
		in.Blue = sim.Army{Formation: sim.F3x2, Units: blue}
		in.RedHealthPct = healthCurve(curve, m)
		// Red: generated by the sim from the seed (as the server does), or chosen by the mode
		if ra := red(seed, blue, stars); len(ra.Units) == 0 {
			in.RedSkills = stars
		} else {
			in.Red = ra
		}
		o, err := sim.Run(in)
		if err != nil {
			panic(err)
		}
		res.vetStars = append(res.vetStars, stars)
		won := o.Result == sim.BlueWin
		res.matchWin = append(res.matchWin, won)
		if !won {
			return res
		}
		res.wins++
		// survivors become veterans and learn one skill each
		vets = vets[:0:0]
		for _, s := range o.Survivors {
			if s.Index < len(blue) {
				u := sim.UnitSpec{Class: blue[s.Index].Class, Skills: append([]sim.Skill(nil), blue[s.Index].Skills...)}
				if len(u.Skills) < sim.MaxSkills {
					u.Skills = append(u.Skills, pickSkill(u, p.picks, rng))
				}
				vets = append(vets, u)
			}
		}
	}
	return res
}

func pickSkill(u sim.UnitSpec, how string, rng *sim.RNG) sim.Skill {
	var left []sim.Skill
	order := bestOrder[u.Class]
	if how == "random" {
		order = nil
		for _, d := range sim.Roster[u.Class].Skills {
			order = append(order, d.Skill)
		}
	}
	for _, s := range order {
		known := false
		for _, k := range u.Skills {
			known = known || k == s
		}
		if !known {
			left = append(left, s)
		}
	}
	if how == "random" {
		return left[rng.IntN(len(left))]
	}
	return left[0]
}

func playRuns(n int, base uint64, p policy, red redMode, curve []int) []runResult {
	out := make([]runResult, n)
	next := make(chan int)
	var wg sync.WaitGroup
	for w := 0; w < runtime.NumCPU(); w++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for i := range next {
				out[i] = playRun(base+uint64(i), p, red, curve)
			}
		}()
	}
	for i := 0; i < n; i++ {
		next <- i
	}
	close(next)
	wg.Wait()
	return out
}

// Runs: run length and per-match win rate for a few policies and Red modes.
func Runs(n int, reds map[string]redMode) string {
	policies := []policy{
		{"2W 2A 1M, random picks", [3]int{2, 2, 1}, "random"},
		{"2W 2A 1M, best picks", [3]int{2, 2, 1}, "best"},
		{"1W 2A 2M, best picks", [3]int{1, 2, 2}, "best"},
		{"3W 0A 2M, best picks", [3]int{3, 0, 2}, "best"},
	}
	var names []string
	for k := range reds {
		names = append(names, k)
	}
	sort.Strings(names)
	var b strings.Builder
	for _, rn := range names {
		fmt.Fprintf(&b, "### Red: %s\n\n| Player policy | Avg wins | Median | Reach match 5 | Reach 10 | Win%% m1 | m2 | m3 | m4–6 | m7+ | Avg ★ at m5 |\n|---|---|---|---|---|---|---|---|---|---|---|\n", rn)
		for _, p := range policies {
			curve := gameCurve // the game's easing, except for modes that replace it
			if strings.HasPrefix(rn, "ramp") {
				curve = nil
			}
			rs := playRuns(n, 500_000, p, reds[rn], curve)
			fmt.Fprintf(&b, "| %s | %s |\n", p.name, summarise(rs))
		}
		b.WriteString("\n")
	}
	fmt.Fprintf(&b, "%d runs per row; a run ends at its first loss (cap %d matches). \"Win%% mX\" is the win rate of match X among runs that reached it.\n", n, maxMatches)
	return b.String()
}

func summarise(rs []runResult) string {
	var wins []int
	reach := func(k int) float64 {
		c := 0
		for _, r := range rs {
			if len(r.matchWin) >= k {
				c++
			}
		}
		return float64(c) / float64(len(rs))
	}
	rate := func(lo, hi int) string {
		w, n := 0, 0
		for _, r := range rs {
			for i, won := range r.matchWin {
				if m := i + 1; m >= lo && m <= hi {
					n++
					if won {
						w++
					}
				}
			}
		}
		if n < 30 {
			return "–"
		}
		return pct(float64(w) / float64(n))
	}
	total, stars5, n5 := 0, 0, 0
	for _, r := range rs {
		wins = append(wins, r.wins)
		total += r.wins
		if len(r.vetStars) >= 5 {
			stars5 += r.vetStars[4]
			n5++
		}
	}
	sort.Ints(wins)
	avgStars := "–"
	if n5 > 0 {
		avgStars = fmt.Sprintf("%.1f", float64(stars5)/float64(n5))
	}
	return fmt.Sprintf("%.2f | %d | %s | %s | %s | %s | %s | %s | %s | %s",
		float64(total)/float64(len(rs)), wins[len(wins)/2], pct(reach(5)), pct(reach(10)),
		rate(1, 1), rate(2, 2), rate(3, 3), rate(4, 6), rate(7, maxMatches), avgStars)
}

var redModes = map[string]redMode{
	"random (the game)":              randomRed,
	"counter-picks (50% of units)":   counterRed,
	"ramp: 3 units m1, 4 m2, then 5": rampRed,
	"ramp: 4 units m1–2, then 5":     ramp4Red,
}

// ramp4Red: 4 Red units in matches 1 and 2, then 5.
func ramp4Red(seed uint64, _ []sim.UnitSpec, skills int) sim.Army {
	a := sim.RedArmy(seed, skills)
	if seed%1000 <= 2 {
		a.Units = a.Units[:4]
	}
	return a
}

// counters[c] is the class that beats c.
var counters = [3]sim.Class{sim.Warrior: sim.Mage, sim.Archer: sim.Warrior, sim.Mage: sim.Archer}

// spreadSkills hands out skills at random over the units, never twice on one.
func spreadSkills(r *sim.RNG, units []sim.UnitSpec, n int) {
	for ; n > 0; n-- {
		var open []int
		for i, u := range units {
			if len(u.Skills) < sim.MaxSkills {
				open = append(open, i)
			}
		}
		if len(open) == 0 {
			return
		}
		u := &units[open[r.IntN(len(open))]]
		var left []sim.Skill
		for _, d := range sim.Roster[u.Class].Skills {
			known := false
			for _, k := range u.Skills {
				known = known || k == d.Skill
			}
			if !known {
				left = append(left, d.Skill)
			}
		}
		u.Skills = append(u.Skills, left[r.IntN(len(left))])
	}
}

// counterRed: each Red unit is, with 50% chance, the counter of the matching
// Blue unit's class, otherwise random.
func counterRed(seed uint64, blue []sim.UnitSpec, skills int) sim.Army {
	r := sim.NewRNG(seed ^ 0xc0)
	a := sim.Army{Formation: sim.Presets[r.IntN(len(sim.Presets))]}
	for i := 0; i < sim.ArmySize; i++ {
		c := sim.Class(r.IntN(3))
		if r.IntN(2) == 0 && i < len(blue) {
			c = counters[blue[i].Class]
		}
		a.Units = append(a.Units, sim.UnitSpec{Class: c})
	}
	sort.SliceStable(a.Units, func(i, j int) bool { return a.Units[i].Class < a.Units[j].Class })
	spreadSkills(r, a.Units, skills)
	return a
}

// rampRed: the game's own Red army, cut to 3 units in match 1 and 4 in match 2.
func rampRed(seed uint64, _ []sim.UnitSpec, skills int) sim.Army {
	a := sim.RedArmy(seed, skills)
	match := int(seed % 1000)
	if size := match + 2; size < len(a.Units) {
		a.Units = a.Units[:size]
	}
	return a
}

// gameCurve is the game's own easing (sim.RunRedHealth) for the first matches.
var gameCurve = []int{sim.RunRedHealth(1), sim.RunRedHealth(2), sim.RunRedHealth(3)}

// healthCurve returns Red's health % for match m (1-based); nil means 100%.
func healthCurve(curve []int, m int) int {
	if m-1 < len(curve) {
		return curve[m-1]
	}
	return 0
}

// RunCurves: the game's random Red with different early-match health curves.
func RunCurves(n int) string {
	curves := []struct {
		name  string
		curve []int
	}{
		{"none (0.4.0 before run-balance)", nil},
		{"90/95%", []int{90, 95}},
		{"85/90/95% (the game now)", gameCurve},
		{"80/88/94%", []int{80, 88, 94}},
		{"80/85/90/95%", []int{80, 85, 90, 95}},
	}
	p := policy{"2W 2A 1M, best picks", [3]int{2, 2, 1}, "best"}
	var b strings.Builder
	b.WriteString("Player: 2W 2A 1M, best picks; Red: the game's random army with its health scaled in the first matches.\n\n| Red health curve | Avg wins | Median | Reach match 5 | Reach 10 | Win% m1 | m2 | m3 | m4–6 | m7+ | Avg ★ at m5 |\n|---|---|---|---|---|---|---|---|---|---|---|\n")
	for _, c := range curves {
		fmt.Fprintf(&b, "| %s | %s |\n", c.name, summarise(playRuns(n, 600_000, p, randomRed, c.curve)))
	}
	fmt.Fprintf(&b, "\n%d runs per row.\n", n)
	return b.String()
}

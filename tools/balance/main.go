// balance: batch-simulate seeded battles and print a Markdown report.
//
//	go run ./tools/balance -n 2000 > docs/balance-report.md   (or: pnpm balance)
//	go run ./tools/balance -unit <name>                       (or: pnpm balance:unit <name>)
//
// It runs at low priority on half the CPUs; -cpu N uses N (e.g. -cpu 16 for all of them).
package main

import (
	"flag"
	"fmt"
	"os"
	"strings"
	"time"

	"chill/sim"
)

func main() {
	n := flag.Int("n", 2000, "battles per experiment row")
	exp := flag.String("exp", "", "only these experiments, comma separated (side,matchups,comps,skills,runs,curves,plans,maps,edges,custom); for quick tuning")
	unit := flag.String("unit", "", "check one roster entry against the new-unit balance bands (pnpm balance:unit <name>)")
	cpu := flag.Int("cpu", workers, "battles run at once (default: half the CPUs)")
	flag.Parse()
	workers = max(1, *cpu)
	lowerPriority()
	start := time.Now()
	if *unit != "" {
		report, ok, err := UnitReport(*unit, *n/2)
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(2)
		}
		fmt.Print(report)
		fmt.Fprintf(os.Stderr, "done in %s\n", time.Since(start).Round(time.Second))
		if !ok {
			os.Exit(1)
		}
		return
	}
	if *exp != "" { // tuning mode: just the tables asked for
		for _, e := range strings.Split(*exp, ",") {
			switch e {
			case "side":
				s, _ := SideBias(*n)
				fmt.Print(s)
			case "matchups":
				s, _ := Matchups(*n)
				fmt.Print(s)
			case "comps":
				s, rows := Compositions(*n / 4)
				fmt.Print(s, Lengths(rows))
			case "skills":
				s, _ := Skills(*n * 2)
				fmt.Print(s)
			case "runs":
				fmt.Print(Runs(*n, redModes))
			case "curves":
				fmt.Print(RunCurves(*n))
			case "plans":
				fmt.Print(PlanMatrix(*n))
			case "maps":
				fmt.Print(MapEffects(*n))
			case "edges":
				fmt.Print(EdgeCheck(*n))
			case "custom":
				fmt.Print(CustomSearch(*n))
			}
		}
		fmt.Fprintf(os.Stderr, "done in %s\n", time.Since(start).Round(time.Second))
		return
	}
	side, _ := SideBias(*n)
	match, _ := Matchups(*n)
	comp, rows := Compositions(*n / 4)
	skills, _ := Skills(*n * 2)
	w := os.Stdout
	fmt.Fprintf(w, "# Balance report\n\nGenerated by `pnpm balance` (`tools/balance`) for sim **%s**. Seeds are fixed, so the numbers are reproducible; rerun after any rule change and compare.\n\n", sim.Version)
	fmt.Fprintf(w, "What these numbers mean, and the balance candidates: see docs/balance-findings.md.\n\n")
	fmt.Fprintf(w, "## Side bias\n\nIdentical armies and formations on both sides (mixes 2W2A1M, 5W, 5A; all 7 presets). A fair sim gives ~50%% each.\n\n%s\n", side)
	fmt.Fprintf(w, "## Class matchups\n\n%s\n", match)
	fmt.Fprintf(w, "## Compositions\n\n%s\n%s\n", comp, Lengths(rows))
	fmt.Fprintf(w, "## Skill impact\n\n%s\n", skills)
	fmt.Fprintf(w, "## Battle plans\n\n%s\n", PlanMatrix(*n/10))
	fmt.Fprintf(w, "## Runs\n\nWhole runs played like the server does: veterans first, then recruits; one new skill per survivor after each win; Red gets as many skills as the veterans have, and the game's early-match health easing applies, except to the \"ramp\" modes, which are alternatives to it. Red modes other than \"random\" are experiments, not the game.\n\n%s\n", Runs(*n/5, redModes))
	fmt.Fprintf(w, "### Early-match easing\n\n%s\n", RunCurves(*n/2))
	fmt.Fprintf(os.Stderr, "done in %s\n", time.Since(start).Round(time.Second))
}
